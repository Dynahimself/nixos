local auto = require("automation")
local M = {}

function M.setup()
    -- Resize (SUPER + R)
    hl.define_submap("resize", function()
        hl.bind("n",           hl.dsp.window.resize({ x = -45, y = 0 }),   { repeating = true, desc = "Resize Narrower" })
        hl.bind("o",           hl.dsp.window.resize({ x = 45,  y = 0 }),   { repeating = true, desc = "Resize Wider" })
        hl.bind("i",           hl.dsp.window.resize({ x = 0,   y = -45 }), { repeating = true, desc = "Resize Shorter" })
        hl.bind("e",           hl.dsp.window.resize({ x = 0,   y = 45 }),  { repeating = true, desc = "Resize Taller" })
        hl.bind("left",        hl.dsp.window.resize({ x = -45, y = 0 }),   { repeating = true, desc = "Resize Narrower" })
        hl.bind("right",       hl.dsp.window.resize({ x = 45,  y = 0 }),   { repeating = true, desc = "Resize Wider" })
        hl.bind("up",          hl.dsp.window.resize({ x = 0,   y = -45 }), { repeating = true, desc = "Resize Shorter" })
        hl.bind("down",        hl.dsp.window.resize({ x = 0,   y = 45 }),  { repeating = true, desc = "Resize Taller" })

        hl.bind("SHIFT + n",   hl.dsp.window.resize({ x = -12, y = 0 }),   { repeating = true, desc = "Fine Narrower" })
        hl.bind("SHIFT + o",   hl.dsp.window.resize({ x = 12,  y = 0 }),   { repeating = true, desc = "Fine Wider" })
        hl.bind("SHIFT + i",   hl.dsp.window.resize({ x = 0,   y = -12 }), { repeating = true, desc = "Fine Shorter" })
        hl.bind("SHIFT + e",   hl.dsp.window.resize({ x = 0,   y = 12 }),  { repeating = true, desc = "Fine Taller" })

        hl.bind("c",           function() auto.float_center_focus() end,   { desc = "Center Float 70%" })
        hl.bind("s",           hl.dsp.layout("togglesplit"),               { desc = "Toggle Split" })
        hl.bind("f",           hl.dsp.window.float({ action = "toggle" }), { desc = "Toggle Float" })
        hl.bind("p",           hl.dsp.window.pseudo(),                     { desc = "Toggle Pseudo" })

        hl.bind("Escape",      hl.dsp.submap("reset"), { desc = "Exit Resize Mode" })
        hl.bind("Return",      hl.dsp.submap("reset"), { desc = "Exit Resize Mode" })
        hl.bind("SUPER + R",   hl.dsp.submap("reset"), { desc = "Exit Resize Mode" })
    end)

    -- Group (SUPER + SHIFT + G)
    hl.define_submap("group", function()
        hl.bind("t",                 hl.dsp.group.toggle(),              { desc = "Toggle Window Group" })
        hl.bind("n",                 hl.dsp.group.prev(),                { desc = "Previous Group Tab" })
        hl.bind("o",                 hl.dsp.group.next(),                { desc = "Next Group Tab" })
        hl.bind("left",              hl.dsp.group.prev(),                { desc = "Previous Group Tab" })
        hl.bind("right",             hl.dsp.group.next(),                { desc = "Next Group Tab" })
        hl.bind("l",                 hl.dsp.group.lock_active("toggle"), { desc = "Lock Active Group" })
        hl.bind("SHIFT + n",         hl.dsp.group.move_window("l"),      { desc = "Move Window Left Into/Out of Group" })
        hl.bind("SHIFT + e",         hl.dsp.group.move_window("d"),      { desc = "Move Window Down Into/Out of Group" })
        hl.bind("SHIFT + i",         hl.dsp.group.move_window("u"),      { desc = "Move Window Up Into/Out of Group" })
        hl.bind("SHIFT + o",         hl.dsp.group.move_window("r"),      { desc = "Move Window Right Into/Out of Group" })
        hl.bind("Escape",            hl.dsp.submap("reset"),             { desc = "Exit Group Mode" })
        hl.bind("Return",            hl.dsp.submap("reset"),             { desc = "Exit Group Mode" })
        hl.bind("SUPER + SHIFT + G", hl.dsp.submap("reset"),             { desc = "Exit Group Mode" })
    end)

    -- Layout (SUPER + Z)
    hl.define_submap("layout", function()
        hl.bind("d",         function() auto.cycle_layout("dwindle");   hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Dwindle Layout" })
        hl.bind("m",         function() auto.cycle_layout("master");    hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Master Layout" })
        hl.bind("s",         function() auto.cycle_layout("scrolling"); hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Scrolling Layout" })
        hl.bind("g",         function() auto.toggle_smart_gaps();       hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Toggle Smart Gaps" })
        hl.bind("c",         function() auto.float_center_focus();      hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Center Float 70%" })
        hl.bind("o",         function() auto.toggle_opaque();           hl.dispatch(hl.dsp.submap("reset")) end, { desc = "Toggle Opaque" })
        hl.bind("p",         hl.dsp.window.pseudo(),                                                             { desc = "Toggle Pseudo" })
        hl.bind("equal",     function() auto.zoom_delta(0.35) end,  { repeating = true, desc = "Zoom In" })
        hl.bind("minus",     function() auto.zoom_delta(-0.35) end, { repeating = true, desc = "Zoom Out" })
        hl.bind("0",         function() auto.zoom_reset() end,      { desc = "Reset Zoom" })
        hl.bind("Escape",    hl.dsp.submap("reset"),                { desc = "Exit Layout Mode" })
        hl.bind("Return",    hl.dsp.submap("reset"),                { desc = "Exit Layout Mode" })
        hl.bind("SUPER + Z", hl.dsp.submap("reset"),                { desc = "Exit Layout Mode" })
    end)
end

return M
